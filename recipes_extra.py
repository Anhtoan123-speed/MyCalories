def _ingredient_lines(items, seasoning):
    lines = []
    for key, grams in items.items():
        if key == "Oil":
            lines.append(f"{grams} g dầu ăn ({grams // 5} thìa cà phê)")
        elif key == "Egg":
            lines.append(f"{grams} g trứng gà ({max(grams // 50, 1)} quả)")
        else:
            lines.append(f"{grams} g {_VI[key]}")
    if seasoning:
        lines.append(seasoning)
    return lines


def _r(name, items, meals, time, seasoning, steps, tip, servings=2):
    return {
        "name": name, "items": items, "servings": servings, "meals": tuple(meals), "time": time,
        "ingredients": _ingredient_lines(items, seasoning), "steps": steps, "tips": [tip],
    }


